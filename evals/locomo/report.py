"""Render evals/locomo/results.json into evals/locomo/RESULTS.md.

The summary block between ``<!-- summary:start -->`` and ``<!-- summary:end -->``
is also what the README and docs quote verbatim.

Paired comparisons use a two-sided paired bootstrap over questions (10 000
resamples, fixed seed) on the per-question reciprocal rank.
"""

from __future__ import annotations

import argparse
import json
import random
import statistics
from pathlib import Path

HERE = Path(__file__).parent
KEYS = ("R@1", "R@5", "R@10", "MRR")
CATS = ("single-hop", "multi-hop", "temporal", "open-domain", "adversarial")


def _rr(row) -> float:
    return 1.0 / min(row[2]) if row[2] else 0.0


def _r(row, k: int) -> float:
    return sum(1 for x in row[2] if x <= k) / row[3]


def paired(a: dict, b: dict, metric: str = "MRR", n: int = 10_000, seed: int = 7) -> tuple[float, float, float]:
    """(mean difference a-b, 95% CI lo, hi) by paired bootstrap."""
    f = _rr if metric == "MRR" else (lambda r: _r(r, int(metric.split("@")[1])))
    da = [f(r) for r in a["per_question"]]
    db = [f(r) for r in b["per_question"]]
    d = [x - y for x, y in zip(da, db)]
    rng = random.Random(seed)
    m = len(d)
    boots = sorted(statistics.fmean(d[rng.randrange(m)] for _ in range(m)) for _ in range(n))
    return statistics.fmean(d), boots[int(0.025 * n)], boots[int(0.975 * n)]


def fmt_ms(m: dict) -> str:
    o = m["overall"]
    s = m["across_conversations"]
    return " | ".join([f"{o[k]:.3f}" for k in KEYS] + [f"{s['MRR']['mean']:.3f} ± {s['MRR']['std']:.3f}"])


def render(res: dict) -> str:
    M = res["methods"]
    meta = res["meta"]
    main = [n for n, m in M.items() if m["group"] == "main"]
    abl = [n for n, m in M.items() if m["group"] == "ablation"]
    L = []
    L.append("# LoCoMo retrieval results\n")
    L.append("Generated by `python -m evals.locomo.report` from `results.json` "
             "(produced by `python -m evals.locomo.run`). Do not edit by hand.\n")
    L.append("<!-- summary:start -->")
    L.append(f"**LoCoMo evidence retrieval** ({meta['conversations']} conversations, "
             f"{meta['memories']} dialog turns as memories, {meta['questions']} questions with "
             "evidence). Recall@k = share of a question's evidence turns in the top k; "
             "MRR = 1/rank of the first evidence turn. *Per-conv MRR* = mean ± std over the "
             "10 conversations (for `+learned` methods these are the 10 leave-one-conversation-out "
             "folds: usefulness learned only from the other 9 conversations' QA feedback).\n")
    L.append("| method | R@1 | R@5 | R@10 | MRR | per-conv MRR |")
    L.append("|---|---|---|---|---|---|")
    for n in main:
        L.append(f"| `{n}` | {fmt_ms(M[n])} |")
    L.append("")
    if "bm25" in M:
        cmp_rows = []
        for n in main:
            if n == "bm25":
                continue
            d, lo, hi = paired(M[n], M["bm25"])
            sig = "yes" if lo > 0 or hi < 0 else "no"
            cmp_rows.append(f"| `{n}` | {d:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {sig} |")
        L.append("Paired difference in MRR vs `bm25` (bootstrap over questions, 95% CI):\n")
        L.append("| method | ΔMRR | 95% CI | significant |")
        L.append("|---|---|---|---|")
        L += cmp_rows
        L.append("")
    L.append("<!-- summary:end -->\n")

    L.append("## Methods\n")
    for n in main + abl:
        L.append(f"- `{n}`: {M[n]['description']}")
    L.append("")
    L.append("## Per question category (MRR / R@5)\n")
    L.append("Category names follow the codes in `locomo10.json` (1 multi-hop, 2 temporal, "
             "3 open-domain, 4 single-hop, 5 adversarial).\n")
    L.append("| method | " + " | ".join(f"{c} (n={meta['questions_per_category'][c]})" for c in CATS) + " |")
    L.append("|---|" + "---|" * len(CATS))
    for n in main:
        pc = M[n]["per_category"]
        L.append(f"| `{n}` | " + " | ".join(
            f"{pc[c]['MRR']:.3f} / {pc[c]['R@5']:.3f}" if pc[c].get("n") else "-" for c in CATS) + " |")
    L.append("")
    L.append("## Ablations\n")
    L.append("Each row removes or isolates components of the lexical HeapDB score "
             "(`+learned` = usefulness learned with leave-one-conversation-out).\n")
    L.append("| ablation | R@1 | R@5 | R@10 | MRR | per-conv MRR |")
    L.append("|---|---|---|---|---|---|")
    for n in ["bm25", "heapdb", "heapdb+learned"] + abl:
        if n in M:
            L.append(f"| `{n}` | {fmt_ms(M[n])} |")
    L.append("")
    if res.get("tuned_choices"):
        L.append("## Nested-CV tuning choices\n")
        L.append("For `+tuned` methods the weights were picked per fold by MRR on the 9 training "
                 "conversations (no learning during tuning), from the grid in `run.py` (`TUNE_GRID`).\n")
        for n, rows in res["tuned_choices"].items():
            L.append(f"`{n}`:\n")
            L.append("| held-out | chosen | train MRR |")
            L.append("|---|---|---|")
            for r in rows:
                p = ", ".join(f"{k}={v:g}" for k, v in r["params"].items())
                L.append(f"| {r['test']} | {p} | {r['train_mrr']:.3f} |")
            L.append("")
    L.append("## Latency per recall\n")
    L.append(f"Single process, Python {meta['python']}, {meta['machine']}; top-50 recall from a "
             "namespace of 369-689 memories (one LoCoMo conversation). Embedding methods include "
             "embedding the query with the ONNX MiniLM model (memory vectors are precomputed).\n")
    L.append("| method | median ms | p95 ms |")
    L.append("|---|---|---|")
    for n in main:
        lt = M[n]["latency_ms"]
        L.append(f"| `{n}` | {lt['median']:.2f} | {lt['p95']:.2f} |")
    L.append("")
    L.append("## Setup\n")
    emb = meta.get("embedder")
    L.append(f"- Dataset: `locomo10.json`, sha256 `{meta['dataset_sha256']}`, downloaded at run time "
             "(CC BY-NC 4.0, not redistributed).")
    L.append(f"- Excluded: {meta['excluded'].get('no_evidence', 0)} questions without evidence "
             f"(category 3); {meta['excluded'].get('evidence_not_found', 0)} whose evidence ids do "
             f"not exist; {meta['excluded'].get('evidence_partly_dropped', 0)} kept with an "
             "unresolvable evidence id dropped. Malformed ids like `D8:6; D9:17` and `D:11:26` are parsed.")
    L.append("- Memory = `\"<speaker>: <text>\"` plus `[shares <caption>]` for image turns; "
             "kind `episode`, source = speaker, created at session time + 1 min per turn. "
             "Query time = 1 day after the last session.")
    L.append(f"- Ranking depth {meta['depth']}; training feedback: recall top {meta['train_shown']} per "
             "training question, `mark_used` the evidence turns among them, `mark_ignored` the rest.")
    if emb:
        L.append(f"- Embeddings: sentence-transformers all-MiniLM-L6-v2, ONNX export, "
                 f"sha256 `{emb['onnx_sha256']}`, run with `OnnxEmbedder` (mean pooling, L2 norm).")
    else:
        L.append("- Embeddings: not measured in this run.")
    L.append(f"- Runtime {meta['runtime_s']} s.")
    L.append("")
    return "\n".join(L) + "\n"


def _d(M, a, b, metric="MRR"):
    if a not in M or b not in M:
        return None
    return paired(M[a], M[b], metric)


def _fd(t) -> str:
    return f"{t[0]:+.3f} | [{t[1]:+.3f}, {t[2]:+.3f}]"


def analysis(res: dict) -> str:
    """Interpretation section. Every number is computed from ``res``; the
    qualitative wording (e.g. "hurts", "main gain") was written for the
    committed results and should be re-read if the results change."""
    M = res["methods"]
    need = ["bm25", "heapdb", "heapdb+learned", "heapdb+learned+tuned", "abl:bm25+importance",
            "abl:bm25+learned", "abl:-recency"]
    if any(n not in M for n in need):
        return ""
    L = ["## Analysis\n", "### Where the gains come from\n",
         f"Paired bootstrap over the {M['bm25']['overall']['n']} questions:\n",
         "| comparison | ΔMRR | 95% CI | reading |", "|---|---|---|---|"]
    rows = [
        ("abl:bm25+importance", "bm25", "the length heuristic for importance (every LoCoMo memory is "
         "an `episode`, so the kind adds nothing) helps a little"),
        ("abl:bm25+learned", "bm25", "**learned usefulness is the main gain**"),
        ("abl:-recency", "abl:bm25+learned", "importance and learning add up"),
        ("heapdb+learned+tuned", "abl:-recency", "nested-CV tuning ends up at recency (almost) off, "
         "so it ties with the hand-made ablation"),
        ("bm25+embedding+tuned", "bm25", "MiniLM embeddings help modestly, and only mixed with BM25"),
        ("heapdb+emb+learned+tuned", "bm25+embedding+tuned", "**at equal relevance and equal tuning, "
         "HeapDB scoring + learning on top of hybrid retrieval**"),
        ("heapdb+emb+learned+tuned", "heapdb+learned+tuned", "embeddings on top of the lexical HeapDB system"),
        ("heapdb", "abl:bm25+importance", "**the default 30-day recency decay hurts on LoCoMo**"),
        ("heapdb+learned", "bm25", "defaults + learning vs plain BM25"),
    ]
    for a, b, txt in rows:
        t = _d(M, a, b)
        if t is not None:
            L.append(f"| `{a}` vs `{b}` | {_fd(t)} | {txt} |")
    L.append("")
    cats = [(c, M["abl:bm25+learned"]["per_category"][c]["MRR"] - M["bm25"]["per_category"][c]["MRR"])
            for c in CATS]
    L.append("Learning by category (`abl:bm25+learned` minus `bm25`, MRR): "
             + ", ".join(f"{c} {d:+.3f}" for c, d in cats) + ".\n")
    ll = res.get("learned_links")
    if ll:
        L.append("### What was learned\n")
        L.append(f"Global `useful` links (shape features) after training on every conversation except "
                 f"{ll['held_out']} (prior mean {ll['prior_mean']:.3f}). Strongest:\n")
        L.append("| feature | P(useful) | evidence n |")
        L.append("|---|---|---|")
        for r in ll["strongest"]:
            L.append(f"| `{r['feature']}` | {r['strength']:.4f} | {r['n']:.0f} |")
        L.append("\nWeakest:\n")
        L.append("| feature | P(useful) | evidence n |")
        L.append("|---|---|---|")
        for r in ll["weakest"]:
            L.append(f"| `{r['feature']}` | {r['strength']:.4f} | {r['n']:.0f} |")
        L.append("")
        L.append(
            "The model learns *which kinds of memory are useful for which kinds of question*: a "
            "turn with a date for a *when* question (`qt:when&date:yes`), a number for *how many* "
            "(`qt:howmany&num:yes`), a turn by the person the question names (`qsrc:yes` vs "
            "`qsrc:no`), and not turns that are themselves questions (`q:yes`). These patterns "
            "carry over to a conversation the model has never seen, and that is where the "
            "held-out gain comes from. The held-out namespace gets no feedback at all: it borrows "
            "the pooled global links through HeapDB's hierarchical prior. The per-memory links "
            "(`mem:<id>`) cannot contribute on held-out data (those memories never got feedback). "
            "They only matter in real use, where the same memories are recalled repeatedly.\n")
    tc = res.get("tuned_choices", {})
    rec = [c["params"].get("w_recency") for n in ("heapdb+learned+tuned", "heapdb+emb+learned+tuned")
           for c in tc.get(n, [])]
    lex = sorted({c["params"].get("lexical_weight") for n in tc for c in tc[n]
                  if "lexical_weight" in c["params"]})
    L.append("### Where HeapDB does not help (or hurts)\n")
    rd = _d(M, "heapdb", "abl:bm25+importance")
    L.append(
        f"- **Recency.** LoCoMo questions ask about any point in a 6-10 month history, all at one "
        f"query time, and no memory is re-used before the test query. So time since last use "
        f"carries no signal here. The default `w_recency=1` (half-life 30 d, floor 0.5) costs "
        f"{rd[0]:+.3f} MRR, and `recency`-only scores {M['recency']['overall']['MRR']:.3f}. Nested-CV "
        f"tuning picked `w_recency=0` in {sum(1 for r in rec if r == 0)} of {len(rec)} fold choices "
        f"(else {sorted(set(r for r in rec if r))}). Recency should matter for temporally local agent "
        "queries (\"what did we decide yesterday\") and with `mark_used` reinforcement. This benchmark "
        "cannot show that, and we do not claim it. For archive-style recall over long histories, set "
        "`w_recency=0`.")
    ld = _d(M, "heapdb+learned", "bm25")
    L.append(
        f"- **Untuned defaults do not beat plain BM25.** `heapdb` scores "
        f"{M['heapdb']['overall']['MRR']:.3f} vs {M['bm25']['overall']['MRR']:.3f} for BM25 (recency "
        f"alone explains the gap). `heapdb+learned` with defaults: ΔMRR {ld[0]:+.3f} "
        f"[{ld[1]:+.3f}, {ld[2]:+.3f}]. The gains need learning *and* a recency weight that fits "
        "the workload.")
    if "bm25+embedding" in M:
        hd = _d(M, "bm25+embedding", "bm25")
        L.append(
            f"- **Hybrid relevance with a fixed 50/50 mix** ties BM25 (ΔMRR {hd[0]:+.3f} "
            f"[{hd[1]:+.3f}, {hd[2]:+.3f}]). The default `heapdb+emb` rows are worse than the lexical "
            f"ones. Tuning chose BM25 share {lex} in every fold.")
        L.append(
            f"- **Embedding-only retrieval** (all-MiniLM-L6-v2, MRR {M['embedding']['overall']['MRR']:.3f}) "
            "is far below BM25: LoCoMo questions reuse the names and nouns of their evidence, and "
            "MiniLM-L6 is small. A stronger embedder would likely narrow the gap; we did not test one.")
    else:
        L.append("- **Embeddings were not measured in this run.**")
    od = dict(cats)["open-domain"]
    L.append(
        f"- **Open-domain questions** (inference or world knowledge) gain little ({od:+.3f} from "
        "learning). Evidence that shares neither words nor features with the question stays hard to find.")
    best = max((n for n in M if M[n]["group"] == "main"), key=lambda n: M[n]["overall"]["MRR"])
    L.append(
        f"- **Absolute numbers are modest.** The best row (`{best}`) puts "
        f"{M[best]['overall']['R@5']:.1%} of evidence turns in the top 5 (R@5). The lift from learning is real but "
        "small (a few hundredths of MRR), in line with earlier HeapDB benchmarks where timing and dose "
        "mattered more than learning.\n")
    L.append("### Threats to validity\n")
    L.append("- Training feedback is *oracle* feedback: the evidence turns among the top 10 are "
             "marked used, and the rest ignored. Real agent feedback (what it actually cited) will be "
             "noisier and sparser.")
    L.append("- Category names are read off the questions (the file has only codes 1-5). The mapping "
             "is the one commonly used for LoCoMo.")
    L.append("- The tuning grids (`TUNE_GRID`, `TUNE_LEXICAL` in `run.py`) are small and were fixed "
             "in advance. Only training-fold MRR picks from them.")
    L.append("- Latency is single-threaded Python on a shared VM: an order of magnitude, not a "
             "benchmark.")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--results", type=Path, default=HERE / "results.json")
    p.add_argument("--out", type=Path, default=HERE / "RESULTS.md")
    a = p.parse_args(argv)
    res = json.loads(a.results.read_text())
    md = render(res) + "\n" + analysis(res)
    a.out.write_text(md)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
