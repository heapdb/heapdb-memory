"""Render evals/locomo/results.json into evals/locomo/RESULTS.md.

The summary block between ``<!-- summary:start -->`` and ``<!-- summary:end -->``
is also what the README and docs quote verbatim.

Paired comparisons use a two-sided paired bootstrap over questions (10 000
resamples, fixed seed) on the per-question reciprocal rank.
"""

from __future__ import annotations

