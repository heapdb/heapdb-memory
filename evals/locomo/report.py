import json
import math
import random
import statistics
from array import array
from pathlib import Path

HERE = Path(__file__).parent
KEYS = ("R@1", "R@5", "R@10", "MRR")
CATS = ("single-hop", "multi-hop", "temporal", "open-domain", "adversarial")


def _rr(row) -> float:
    return 1.0 / min(row[2]) if row[2] else 0.0


def _r(row, k: int) -> float:
    return sum(1 for x in row[2] if x <= k) / row[3]


def paired(a: dict, b: dict, metric: str = "MRR", n: int = 10_000, seed: int = 7) -> tuple[float, float, float]:
    """(mean difference a-b, 95% CI lo, hi) by paired bootstrap."""
    f = _rr if metric == "MRR" else (lambda r: _r(r, int(metric.split("@")[1])))
    da = [f(r) for r in a["per_question"]]
    db = [f(r) for r in b["per_question"]]
    d = [x - y for x, y in zip(da, db)]
    rng = random.Random(seed)
    m = len(d)
    boots = sorted(statistics.fmean(d[rng.randrange(m)] for _ in range(m)) for _ in range(n))
    return statistics.fmean(d), boots[int(0.025 * n)], boots[int(0.975 * n)]


_IDX: dict[tuple[int, int, int], list[array]] = {}


def _boot_idx(m: int, n: int, seed: int) -> list[array]:
    if (m, n, seed) not in _IDX:
        rng = random.Random(seed)
        typ = "H" if m < 65536 else "I"
        _IDX[(m, n, seed)] = [array(typ, [rng.randrange(m) for _ in range(m)]) for _ in range(n)]
    return _IDX[(m, n, seed)]


def boot(d: list[float], n: int = 10_000, seed: int = 7) -> tuple[float, float, float]:
    """:func:`paired` for a precomputed per-question difference ``d``: the same
    resamples and the same result, but the resamples are drawn once and reused
    across comparisons."""
    m = len(d)
    g = d.__getitem__
    boots = sorted(math.fsum(map(g, ix)) / m for ix in _boot_idx(m, n, seed))
    return statistics.fmean(d), boots[int(0.025 * n)], boots[int(0.975 * n)]


def fmt_ms(m: dict) -> str:
    o = m["overall"]
    s = m["across_conversations"]
    return " | ".join([f"{o[k]:.3f}" for k in KEYS] + [f"{s['MRR']['mean']:.3f} ± {s['MRR']['std']:.3f}"])


def render(res: dict) -> str:
    M = res["methods"]
    meta = res["meta"]
    main = [n for n, m in M.items() if m["group"] == "main"]
    abl = [n for n, m in M.items() if m["group"] == "ablation"]
    L = []
    L.append("# LoCoMo retrieval results\n")
    L.append("Generated by `python -m evals.locomo.report` from `results.json` "
             "(produced by `python -m evals.locomo.run`). Do not edit by hand.\n")
    L.append("<!-- summary:start -->")
    L.append(f"**LoCoMo evidence retrieval** ({meta['conversations']} conversations, "
             f"{meta['memories']} dialog turns as memories, {meta['questions']} questions with "
             "evidence). Recall@k = share of a question's evidence turns in the top k; "
             "MRR = 1/rank of the first evidence turn. *Per-conv MRR* = mean ± std over the "
             "10 conversations (for `+learned` methods these are the 10 leave-one-conversation-out "
             "folds: usefulness learned only from the other 9 conversations' QA feedback).\n")
    L.append("| method | R@1 | R@5 | R@10 | MRR | per-conv MRR |")
    L.append("|---|---|---|---|---|---|")
    for n in main:
        L.append(f"| `{n}` | {fmt_ms(M[n])} |")
    L.append("")
    if "bm25" in M:
        cmp_rows = []
        for n in main:
            if n == "bm25":
                continue
            d, lo, hi = paired(M[n], M["bm25"])
            sig = "yes" if lo > 0 or hi < 0 else "no"
            cmp_rows.append(f"| `{n}` | {d:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {sig} |")
        L.append("Paired difference in MRR vs `bm25` (bootstrap over questions, 95% CI):\n")
        L.append("| method | ΔMRR | 95% CI | significant |")
        L.append("|---|---|---|---|")
        L += cmp_rows
        L.append("")
    L.append("<!-- summary:end -->\n")

    L.append("## Methods\n")
    for n in main + abl:
        L.append(f"- `{n}`: {M[n]['description']}")
    L.append("")
    L.append("## Per question category (MRR / R@5)\n")
    L.append("Category names follow the codes in `locomo10.json` (1 multi-hop, 2 temporal, "
             "3 open-domain, 4 single-hop, 5 adversarial).\n")
